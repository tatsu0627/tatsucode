import * as THREE from 'three';
import {
  mulberry32, fbm, ridged, warp, blur3, remap, normalize01, clamp01, smoothstep, lerp,
  stampDome, stampBlob, stampSegment, stampCrack, stampStreak,
  normalFromHeight, aoFromHeight,
} from './fields.js';

/**
 * texgen.js — the procedural PBR texture library. Zero external assets.
 *
 * Each entry produces a tiling set:
 *    map        sRGB albedo
 *    normalMap  tangent-space, SOBEL-DERIVED from the same height field that
 *               drives the AO — so cracks, mortar joints and panel seams line
 *               up across all three maps instead of floating independently.
 *    ormMap     R = ambient occlusion (cavity), G = roughness, B = metalness
 *               (the glTF packing; three reads .r/.g/.b for ao/rough/metal, so
 *               one texture and one sampler serves all three)
 *
 * Authoring rule from the art bible: surface detail must exist at THREE
 * frequencies or it reads as plastic —
 *    macro  (0.5-3 m)  large blotches, staining, damage zones, paint loss
 *    meso   (2-20 cm)  cracks, panel seams, mortar, plank edges, dents
 *    micro  (< 1 cm)   aggregate, grain, weave, pitting
 * Every generator below builds all three explicitly.
 *
 * `tileMetres` is the real-world size of one UV tile. Geometry UVs are
 * generated by world-space planar projection divided by this number, so a
 * texture is physically the same size on every surface in the level and the
 * classic "wrong tiling scale" tell cannot happen.
 */

const HEX = (h) => [((h >> 16) & 255) / 255, ((h >> 8) & 255) / 255, (h & 255) / 255];

// palette (sRGB) — mirrors artdirection.PALETTE, kept local so texture authoring
// can nudge a value without editing the bible.
const C = {
  concrete: HEX(0x8f8b83), concreteDark: HEX(0x605d58), concretePale: HEX(0xb0aa9f),
  sand: HEX(0xbfa984), sandDark: HEX(0x8d7a5c), sandPale: HEX(0xd8c6a4),
  rust: HEX(0x7a4a2c), rustLight: HEX(0xa2683c), rustDark: HEX(0x4a2c1c),
  steel: HEX(0x8a8f94), steelDark: HEX(0x5a5f64), zinc: HEX(0x9aa0a4),
  paintedTan: HEX(0xa8916b), asphalt: HEX(0x3f3d3c), asphaltPatch: HEX(0x2c2b2b),
  wood: HEX(0x9b7a4e), woodDark: HEX(0x6a5031), sandbag: HEX(0xa89573),
  brick: HEX(0x8a5a44), brickDark: HEX(0x6b4231), mortar: HEX(0x9c968a),
  plaster: HEX(0xbfb5a4), moss: HEX(0x5c5b46), grime: HEX(0x3a352d),
};

// ---------------------------------------------------------------------------
// albedo helpers — three parallel Float32 planes, sRGB 0..1
// ---------------------------------------------------------------------------
function rgbPlanes(n, c) {
  const R = new Float32Array(n), G = new Float32Array(n), B = new Float32Array(n);
  R.fill(c[0]); G.fill(c[1]); B.fill(c[2]);
  return [R, G, B];
}
function blendMask(P, c, mask, strength = 1, bias = 0) {
  const [R, G, B] = P;
  for (let i = 0; i < R.length; i++) {
    const t = clamp01((mask[i] + bias) * strength);
    R[i] += (c[0] - R[i]) * t; G[i] += (c[1] - G[i]) * t; B[i] += (c[2] - B[i]) * t;
  }
}
function shadeByField(P, f, lo, hi) {
  const [R, G, B] = P;
  for (let i = 0; i < R.length; i++) {
    const k = lo + (hi - lo) * f[i];
    R[i] *= k; G[i] *= k; B[i] *= k;
  }
}
function jitterHue(P, rnd, amt) {
  const [R, G, B] = P;
  for (let i = 0; i < R.length; i++) {
    R[i] *= 1 + (rnd() - 0.5) * amt; G[i] *= 1 + (rnd() - 0.5) * amt; B[i] *= 1 + (rnd() - 0.5) * amt;
  }
}

function toBytes(P, size) {
  const n = size * size, out = new Uint8Array(n * 4);
  const [R, G, B] = P;
  for (let i = 0; i < n; i++) {
    const j = i * 4;
    out[j] = clamp01(R[i]) * 255; out[j + 1] = clamp01(G[i]) * 255; out[j + 2] = clamp01(B[i]) * 255; out[j + 3] = 255;
  }
  return out;
}
function packORM(ao, rough, metal, size) {
  const n = size * size, out = new Uint8Array(n * 4);
  for (let i = 0; i < n; i++) {
    const j = i * 4;
    out[j] = clamp01(ao[i]) * 255;
    out[j + 1] = clamp01(Math.max(0.08, rough[i])) * 255;   // bible: never below 0.08
    out[j + 2] = clamp01(metal[i]) * 255;
    out[j + 3] = 255;
  }
  return out;
}

function makeTex(bytes, size, srgb, aniso) {
  const t = new THREE.DataTexture(bytes, size, size, THREE.RGBAFormat, THREE.UnsignedByteType);
  t.wrapS = t.wrapT = THREE.RepeatWrapping;
  t.magFilter = THREE.LinearFilter;
  t.minFilter = THREE.LinearMipmapLinearFilter;
  t.generateMipmaps = true;
  t.anisotropy = aniso;
  if (srgb) t.colorSpace = THREE.SRGBColorSpace;
  t.needsUpdate = true;
  return t;
}


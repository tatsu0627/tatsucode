const GENERATORS = {
  concrete: { fn: genConcrete, size: 1024 },
  sand: { fn: genSand, size: 1024 },
  asphalt: { fn: genAsphalt, size: 1024 },
  corrugated: { fn: genCorrugated, size: 1024 },
  container: { fn: genContainer, size: 1024 },
  paintedSteel: { fn: genPaintedSteel, size: 1024 },
  plasterBrick: { fn: genPlasterBrick, size: 1024 },
  rustedSteel: { fn: genRustedSteel, size: 512 },
  sandbag: { fn: genSandbag, size: 512 },
  wood: { fn: genWood, size: 512 },
  grating: { fn: genGrating, size: 512 },
  chainlink: { fn: genChainlink, size: 512 },
  tarp: { fn: genTarp, size: 512 },
};

export class TextureLibrary {
  constructor(renderer, opts = {}) {
    this.cache = new Map();
    this.scale = opts.scale ?? 1;
    const maxA = renderer?.capabilities?.getMaxAnisotropy?.() ?? 1;
    this.aniso = Math.min(4, maxA);
    this.stats = { ms: 0, bytes: 0 };
  }

  get(name) {
    if (this.cache.has(name)) return this.cache.get(name);
    const g = GENERATORS[name];
    if (!g) throw new Error(`texgen: unknown texture set "${name}"`);
    const t0 = performance.now();
    const size = Math.max(128, Math.round((g.size * this.scale) / 128) * 128);
    const d = g.fn(size);

    const ao = aoFromHeight(d.height, d.size, 10, 1.15);
    const albedoBytes = toBytes(d.albedo, d.size);
    if (d.alpha) {                    // punch alpha into the albedo texture
      for (let i = 0; i < d.alpha.length; i++) albedoBytes[i * 4 + 3] = clamp01(d.alpha[i]) * 255;
    }
    const set = {
      map: makeTex(albedoBytes, d.size, true, this.aniso),
      normalMap: makeTex(normalFromHeight(d.height, d.size, d.heightMetres, d.tileMetres), d.size, false, this.aniso),
      ormMap: makeTex(packORM(ao, d.rough, d.metal, d.size), d.size, false, this.aniso),
      tileMetres: d.tileMetres,
      heightMetres: d.heightMetres,
      hasAlpha: !!d.alpha,
      size: d.size,
    };
    set.map.name = `${name}_albedo`;
    set.normalMap.name = `${name}_normal`;
    set.ormMap.name = `${name}_orm`;
    this.stats.ms += performance.now() - t0;
    this.stats.bytes += d.size * d.size * 4 * 3;
    this.cache.set(name, set);
    return set;
  }

  /** Warm the whole library up front so nothing hitches mid-frame. */
  preload(names) { for (const n of names) this.get(n); return this; }
}

